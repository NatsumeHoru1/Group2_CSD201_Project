#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""
sync_authors.py
Synchronizes author names and student IDs from PHAN_CONG.md into LaTeX paper files:
- paper/authors.tex (included via \input{authors.tex})
- paper/paper.tex (inline author block fallback)
- C:\Users\ADMIN\Downloads\paper.tex (local copy if present)
"""

import os
import re
import sys
from pathlib import Path

# Set stdout encoding to UTF-8
if sys.stdout.encoding != 'utf-8':
    try:
        sys.stdout.reconfigure(encoding='utf-8')
    except AttributeError:
        pass

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent
PHAN_CONG_FILE = REPO_ROOT / "PHAN_CONG.md"
PAPER_DIR = REPO_ROOT / "paper"
AUTHORS_TEX_FILE = PAPER_DIR / "authors.tex"
PAPER_TEX_FILE = PAPER_DIR / "paper.tex"
DOWNLOADS_PAPER_TEX = Path("C:/Users/ADMIN/Downloads/paper.tex")

# Default metadata and technical roles in English for IEEE conference format
ROLE_DESCRIPTIONS = {
    1: "TV1{id_str} -- Team Leader / Runner, Workload \\& Primary Measurements.",
    2: "TV2{id_str} -- SC Implementation, Hashing, Generator \\& Variant B Analysis.",
    3: "TV3{id_str} -- LP-Tomb Implementation \\& Rebuild Dynamics.",
    4: "TV4{id_str} -- Test Harness, RQ2/RQ3 Workload \\& Repo Administration.",
    5: "TV5{id_str} -- Robin Hood Implementation \\& Paper Framing.",
    6: "TV6{id_str} -- LP-Backshift Implementation, CSV Validator \\& Paper Coordination."
}

DEFAULT_MEMBERS = {
    1: {"name": "Huỳnh Anh Tuấn", "mssv": "QE200073"},
    2: {"name": "Hồ Anh Nhật", "mssv": "QE200301"},
    3: {"name": "Member 3", "mssv": None},
    4: {"name": "Nguyễn Trần Anh Kiệt", "mssv": "QE200105"},
    5: {"name": "Châu Minh Tiến", "mssv": "QE200077"},
    6: {"name": "Võ Ngọc Phú", "mssv": "QE200004"}
}

def parse_phan_cong(file_path):
    if not file_path.exists():
        print(f"[WARN] File not found: {file_path}")
        return DEFAULT_MEMBERS

    with open(file_path, "r", encoding="utf-8") as f:
        text = f.read()

    members = dict(DEFAULT_MEMBERS)
    lines = text.splitlines()

    for line in lines:
        m = re.match(r"^##\s*TV(\d+)\b(.*)", line)
        if not m:
            continue
        tv_num = int(m.group(1))
        if tv_num not in members:
            continue

        rest = m.group(2).strip()
        rest = re.sub(r"^[-:]\s*", "", rest).strip()

        # Extract MSSV (e.g. '(MSSV: QE200073)' or 'MSSV: QE200073' or '(QE200073)')
        mssv_m = re.search(r"\((?:MSSV:?\s*)?([A-Za-z0-9]+)\)", rest, re.IGNORECASE)
        if not mssv_m:
            mssv_m = re.search(r"\bMSSV:?\s*([A-Za-z0-9]+)", rest, re.IGNORECASE)
        mssv = mssv_m.group(1).strip() if mssv_m else None

        # Extract Name
        name = None
        if mssv_m:
            prefix = rest[:mssv_m.start()].strip()
            prefix = re.sub(r"[-–—:]\s*$", "", prefix).strip()
            if prefix:
                name = prefix
        else:
            parts = rest.split(":", 1)
            candidate = parts[0].strip()
            tech_keywords = [
                "linear probing", "tombstone", "runner", "generator", 
                "workload", "robin hood", "backshift", "separate chaining"
            ]
            if not any(k in candidate.lower() for k in tech_keywords) and len(candidate) > 2:
                name = candidate

        if name:
            members[tv_num]["name"] = name
        if mssv:
            members[tv_num]["mssv"] = mssv

    return members

def build_authors_tex(members):
    lines = []
    lines.append("% Auto-generated by bench/sync_authors.py - DO NOT EDIT MANUALLY")
    lines.append("\\author{")
    
    entries = []
    for tv in range(1, 7):
        m = members.get(tv, DEFAULT_MEMBERS[tv])
        name = m.get("name") or f"Member {tv}"
        mssv = m.get("mssv")
        
        id_str = f" (Student ID: {mssv})" if mssv else ""
        role_tpl = ROLE_DESCRIPTIONS.get(tv, "TV" + str(tv) + "{id_str}.")
        role_text = role_tpl.format(id_str=id_str)
        
        entry = f"    \\textbf{{{name}}}\\thanks{{{role_text}}}"
        entries.append(entry)

    # First row: TV1, TV2, TV3
    row1 = ",\n".join(entries[0:3]) + ", \\\\"
    # Second row: TV4, TV5, TV6
    row2 = ",\n".join(entries[3:6]) + " \\\\"
    
    lines.append(row1)
    lines.append(row2)
    lines.append("    \\small FPT University -- Fall 2026 Semester -- Class SE20C -- Group 2 (Variant B)")
    lines.append("}")
    return "\n".join(lines) + "\n"

def sync():
    print(f"Reading author details from: {PHAN_CONG_FILE}")
    members = parse_phan_cong(PHAN_CONG_FILE)
    print("Parsed team members:")
    for tv in sorted(members.keys()):
        info = members[tv]
        print(f"  TV{tv}: {info.get('name')} | Student ID: {info.get('mssv')}")

    authors_content = build_authors_tex(members)
    
    author_block = build_authors_tex(members).replace(
        "% Auto-generated by bench/sync_authors.py - DO NOT EDIT MANUALLY\n", ""
    )

    # 1. Write paper/authors.tex
    PAPER_DIR.mkdir(parents=True, exist_ok=True)
    with open(AUTHORS_TEX_FILE, "w", encoding="utf-8") as f:
        f.write(authors_content)
    print(f"[OK] Generated: {AUTHORS_TEX_FILE}")

    # 2. Update paper/paper.tex if it exists and has an author block
    if PAPER_TEX_FILE.exists():
        with open(PAPER_TEX_FILE, "r", encoding="utf-8") as f:
            paper_content = f.read()

        # If paper.tex has an explicit author block, update it or keep \input{authors.tex}
        if "\\input{authors.tex}" not in paper_content:
            # Replace author block between \author{ and the closing } before \date
            pattern = r"\\author\{.*?\n\}\n"
            if re.search(pattern, paper_content, re.DOTALL):
                paper_content = re.sub(pattern, lambda m: author_block + "\n", paper_content, flags=re.DOTALL)
                with open(PAPER_TEX_FILE, "w", encoding="utf-8") as f:
                    f.write(paper_content)
                print(f"[OK] Updated author block in: {PAPER_TEX_FILE}")
    
    # 3. Update C:\Users\ADMIN\Downloads\paper.tex if it exists
    if DOWNLOADS_PAPER_TEX.exists():
        try:
            with open(DOWNLOADS_PAPER_TEX, "r", encoding="utf-8") as f:
                dl_content = f.read()
            pattern = r"\\author\{.*?\n\}\n"
            if re.search(pattern, dl_content, re.DOTALL):
                dl_content = re.sub(pattern, lambda m: author_block + "\n", dl_content, flags=re.DOTALL)
                with open(DOWNLOADS_PAPER_TEX, "w", encoding="utf-8") as f:
                    f.write(dl_content)
                print(f"[OK] Updated author block in: {DOWNLOADS_PAPER_TEX}")
        except Exception as e:
            print(f"[WARN] Could not update Downloads paper.tex: {e}")

if __name__ == "__main__":
    sync()
